"""Writes the generated sections of a Performance page from a shootout results.json (schema 1).

Usage: shootout-adoc.py <results.json> <out.adoc> [--subject t1,t2] [--spectrum t1,t2,t3,t4]

--subject   the targets the page is about, drawn in the accent colour (default: chappe-jvm,chappe-native)
--spectrum  the targets of the latency spectrum chart, four at most (default: the subjects, helidon, jetty)

The output is an AsciiDoc partial, meant for `include::partial$performance/<version>.adoc[leveloffset=+1]`.
Charts are `[vegalite]` blocks with their data inline: the docs build hands them to Kroki, which returns
static SVG (asciidoctor-kroki, `kroki-fetch-diagram: true`), so the published page needs neither
JavaScript nor Grafana. Tables carry the same figures as the charts, for readers who cannot see them.
"""
import json
import sys

SURFACE = "#fcfcfb"
INK = "#0b0b0b"
INK_SECONDARY = "#52514e"
GRID = "#e8e7e2"
DOMAIN = "#c3c2b7"
ACCENT = "#2a78d6"
CONTEXT = "#8f8e88"
# Categorical slots 1-4, fixed order (dataviz reference palette, adjacent pairs validated in light mode).
CATEGORICAL = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100"]

LABELS = {"chappe-jvm": "Chappe (JVM)", "chappe-native": "Chappe (native)", "helidon": "Helidon SE",
          "jetty": "Jetty", "netty": "Netty", "vertx": "Vert.x", "jdk": "JDK HttpServer",
          "nginx": "nginx", "go": "Go net/http"}

CONFIG = {
    "background": SURFACE,
    "font": "sans-serif",
    "view": {"stroke": None},
    "axis": {"labelColor": INK_SECONDARY, "titleColor": INK_SECONDARY, "gridColor": GRID,
             "domainColor": DOMAIN, "tickColor": DOMAIN, "titleFontWeight": "normal",
             "labelFontSize": 12, "titleFontSize": 12},
    "legend": {"labelColor": INK_SECONDARY, "titleColor": INK_SECONDARY, "labelFontSize": 12},
    "header": {"labelColor": INK, "titleColor": INK_SECONDARY, "labelFontSize": 13},
    "text": {"fontSize": 12},
    "title": {"color": INK, "anchor": "start", "fontWeight": "normal"},
}

PERCENTILE_LABELS = ("datum.value == 2 ? '50%' : datum.value == 10 ? '90%'"
                     " : datum.value == 100 ? '99%' : datum.value == 1000 ? '99.9%'"
                     " : datum.value == 10000 ? '99.99%' : datum.value == 100000 ? '99.999%' : ''")


def label(target):
    return LABELS.get(target, target)


def rate_text(rate):
    return "%gk" % (rate / 1000) if rate >= 1000 else str(rate)


def ms_text(value):
    return "%.2f ms" % value if value < 10 else "%.0f ms" % value


def vegalite(name, spec):
    """A Kroki block; its data points are written one per line, so the partial stays short and diffable."""
    values = spec["data"]["values"]
    spec = dict({"$schema": "https://vega.github.io/schema/vega-lite/v5.json", "config": CONFIG}, **spec)
    spec["data"] = {"values": "@VALUES@"}
    rows = ",\n  ".join(json.dumps(v, separators=(",", ":")) for v in values)
    body = json.dumps(spec, indent=1).replace('"@VALUES@"', "[\n  %s\n ]" % rows)
    return "[vegalite,%s,svg]\n....\n%s\n....\n" % (name, body)


def table(header, rows, cols):
    lines = ['[cols="%s"%s]' % (cols, ',options="header"' if header else ""), "|==="]
    if header:
        lines.append("".join("|%s " % cell for cell in header).rstrip())
    for row in rows:
        lines.append("".join("|%s " % cell for cell in row).rstrip())
    lines.append("|===")
    return "\n".join(lines) + "\n"


def main(results_path, out_path, subjects, spectrum_targets):
    with open(results_path, encoding="utf-8") as fh:
        results = json.load(fh)
    fp = results["fingerprint"]
    slo = fp["params"]["slo_p99_ms"]
    runs, single = {}, {}
    for r in results["results"]:
        rate = r["params"].get("offered_rate")
        if rate is None:
            single.setdefault(r["target"], {})[r["metric"]] = r["value"]
        else:
            runs.setdefault(r["target"], {}).setdefault(rate, {})[r["metric"]] = r["value"]
    targets = [t for t in fp["targets"] if t in runs]

    # A measurement during which other containers used more CPU than the threshold is left out (ADR 0001).
    limit = fp["params"].get("interference_cpu_pct")
    disturbed = []
    if limit is not None:
        for t in targets:
            for rate in sorted(runs[t]):
                if runs[t][rate].get("foreign_cpu_max", 0) > limit:
                    disturbed.append((t, rate, runs[t].pop(rate)["foreign_cpu_max"]))

    def clean(m):
        return m["p99"] < slo and m.get("socket_errors", 0) == 0 and m.get("non_2xx", 0) == 0

    best = {}
    for t in targets:
        passing = [rate for rate, m in runs[t].items() if clean(m)]
        best[t] = max(passing) if passing else 0
    ranked = sorted(targets, key=lambda t: (-best[t], label(t)))
    rates = sorted({rate for t in targets for rate in runs[t]} | {rate for _, rate, _ in disturbed})
    reference = best.get(subjects[0]) or rates[len(rates) // 2]

    out = []
    out.append("// Generated by Vidocq/ci bench-report/shootout-adoc.py from a results.json. Do not edit by hand.\n")
    canonical = fp["host"]["governor"] == "performance" and fp["host"]["no_turbo"] == "1" and not fp["dirty"]
    if not canonical:
        out.append("[WARNING]\n====\nNot a reference run: governor `%s`, turbo %s%s. Its figures show the shape of the "
                   "report, not the performance of a version.\n====\n" % (
                       fp["host"]["governor"], "off" if fp["host"]["no_turbo"] == "1" else "on",
                       ", uncommitted changes in the working tree" if fp["dirty"] else ""))
    if disturbed:
        out.append("[WARNING]\n====\nLeft out, as other containers used more than %g %% of a CPU during the "
                   "measurement: %s. The sustained rate of these servers may be understated.\n====\n" % (
                       limit, ", ".join("%s at %s req/s (%g %%)" % (label(t), rate_text(rate), cpu)
                                        for t, rate, cpu in disturbed)))

    out.append("== Sustained throughput\n")
    out.append("The highest offered rate each server sustains with a p99 latency under %g ms and no error, "
               "among the rates tested (%s req/s). `wrk2` sends at a constant rate, so a server that falls "
               "behind shows it in its latency instead of hiding it in a lower throughput.\n"
               % (slo, ", ".join(rate_text(r) for r in rates)))
    bars = [{"target": label(t), "rate": best[t], "text": rate_text(best[t]) if best[t] else "none",
             "subject": t in subjects} for t in ranked]
    out.append(vegalite("shootout-sustained", {
        "width": 640, "height": {"step": 28},
        "data": {"values": bars},
        "encoding": {"y": {"field": "target", "type": "nominal", "sort": None, "title": None,
                           "axis": {"labelColor": INK, "domain": False, "ticks": False, "labelPadding": 8}}},
        "layer": [
            {"mark": {"type": "bar", "cornerRadiusEnd": 4, "height": {"band": 0.62}},
             "encoding": {"x": {"field": "rate", "type": "quantitative", "title": "req/s, p99 < %g ms" % slo,
                                "axis": {"format": "~s", "grid": True, "tickCount": 5},
                                # Up to the highest rate tested, so the room left above a bar shows.
                                "scale": {"domain": [0, rates[-1]]}},
                          "color": {"condition": {"test": "datum.subject", "value": ACCENT}, "value": CONTEXT}}},
            {"mark": {"type": "text", "align": "left", "dx": 6, "color": INK_SECONDARY},
             "encoding": {"x": {"field": "rate", "type": "quantitative"}, "text": {"field": "text"}}},
        ],
    }))
    rows = []
    for t in ranked:
        m = runs[t].get(best[t]) if best[t] else None
        rows.append([label(t), rate_text(best[t]) if m else "none",
                     ms_text(m["p50"]) if m else "-", ms_text(m["p99"]) if m else "-",
                     ms_text(m["p99.9"]) if m else "-"])
    out.append(table(["Server", "Sustained (req/s)", "p50", "p99", "p99.9"], rows, "3,2,1,1,1"))

    out.append("\n== Latency against load\n")
    out.append("p99 latency of each server at each offered rate, on a logarithmic scale. The dashed line is the "
               "%g ms objective.\n" % slo)
    points = [{"target": label(t), "rate": rate, "p99": runs[t][rate]["p99"], "subject": t in subjects}
              for t in ranked for rate in sorted(runs[t])]
    out.append(vegalite("shootout-capacity", {
        "data": {"values": points},
        "facet": {"field": "target", "type": "nominal", "sort": [label(t) for t in ranked], "title": None},
        "columns": 3,
        "spec": {
            "width": 210, "height": 130,
            "layer": [
                {"mark": {"type": "rule", "strokeDash": [4, 3], "color": INK_SECONDARY, "strokeWidth": 1},
                 "encoding": {"y": {"datum": slo}}},
                {"mark": {"type": "line", "strokeWidth": 2, "point": {"filled": True, "size": 64}},
                 "encoding": {
                     "x": {"field": "rate", "type": "quantitative", "title": "offered req/s",
                           "axis": {"format": "~s", "values": rates}},
                     "y": {"field": "p99", "type": "quantitative", "title": "p99 (ms)",
                           "scale": {"type": "log"}, "axis": {"tickCount": 4}},
                     "color": {"condition": {"test": "datum.subject", "value": ACCENT}, "value": CONTEXT}}},
            ],
        },
        "resolve": {"scale": {"y": "shared"}},
    }))
    left_out = {(t, rate) for t, rate, _ in disturbed}
    rows = [[label(t)] + [ms_text(runs[t][r]["p99"]) if r in runs[t] else "disturbed" if (t, r) in left_out else "-"
                          for r in rates] for t in ranked]
    out.append(table(["Server"] + ["p99 @ %s" % rate_text(r) for r in rates], rows,
                     ",".join(["3"] + ["1"] * len(rates))))

    shown = [t for t in spectrum_targets if t in runs and reference in runs[t]][:4]
    spectrum = [s for s in results["series"]
                if s["kind"] == "latency_spectrum" and s["target"] in shown
                and s["params"].get("offered_rate") == reference]
    if spectrum:
        out.append("\n== Latency spectrum at %s req/s\n" % rate_text(reference))
        out.append("The full HdrHistogram distribution at %s req/s: how latency grows towards the rarest requests. "
                   "The horizontal axis is the percentile, on a scale that gives each extra nine the same width.\n"
                   % rate_text(reference))
        values = [{"target": label(s["target"]), "x": 1.0 / (1.0 - p), "ms": v}
                  for s in spectrum for p, v in s["points"] if p >= 0.5]
        domain = [label(t) for t in shown]
        out.append(vegalite("shootout-spectrum", {
            "width": 680, "height": 300,
            "data": {"values": values},
            "encoding": {
                "x": {"field": "x", "type": "quantitative", "title": "percentile",
                      "scale": {"type": "log"},
                      "axis": {"values": [2, 10, 100, 1000, 10000, 100000], "labelExpr": PERCENTILE_LABELS}},
                "y": {"field": "ms", "type": "quantitative", "title": "latency (ms)", "scale": {"type": "log"}},
                "color": {"field": "target", "type": "nominal", "title": None,
                          "scale": {"domain": domain, "range": CATEGORICAL[:len(domain)]},
                          "legend": {"orient": "top", "direction": "horizontal"}}},
            # No end-of-line labels: close curves make them collide, and the legend names all four.
            "mark": {"type": "line", "strokeWidth": 2},
        }))

    out.append("\n== Footprint\n")
    rows = [[label(t), "%.0f MiB" % single[t]["image_size"] if "image_size" in single.get(t, {}) else "-",
             "%.1f MiB" % single[t]["idle_rss"] if "idle_rss" in single.get(t, {}) else "-"] for t in ranked]
    out.append(table(["Server", "Container image", "Idle RSS"], rows, "3,1,1"))

    host = fp["host"]
    out.append("\n== Run environment\n")
    rows = [
        ["Date", fp["date"]],
        ["Commit", "`%s`%s" % (fp["commit"][:12], " (uncommitted changes)" if fp["dirty"] else "")],
        ["Machine", "%s, %d logical CPUs, %.0f GiB" % (host["cpu_model"], host["logical_cpus"],
                                                       host["memory_kb"] / 1024 / 1024)],
        ["CPU settings", "governor `%s`, turbo %s" % (host["governor"], "off" if host["no_turbo"] == "1" else "on")],
        ["Kernel, Docker", "%s, Docker %s" % (host["kernel"], host["docker"])],
        ["JVM", fp["jvm"]],
        ["Mode", "%s%s" % (fp["mode"], ", servers on CPUs `%s`, client on `%s`" % (
            fp["cpusets"]["server"], fp["cpusets"]["client"]) if fp.get("cpusets") else "")],
        ["Load", "`wrk2`, %d threads, %d connections, %s per rate after a %s warm-up at up to %s req/s; "
                 "a fresh container for every rate" % (fp["params"]["threads"], fp["params"]["connections"],
                                                       fp["params"]["duration"], fp["params"]["warmup"],
                                                       rate_text(fp["params"]["warmup_rate"]))],
        ["Client", "`%s`" % fp.get("client", "wrk2")],
    ]
    rows += [[label(t), fp["targets"][t] if t != "chappe-jvm" else "commit above"] for t in targets]
    out.append(table(None, rows, "1,3"))

    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))


if __name__ == "__main__":
    args = sys.argv[1:]
    options = {"--subject": "chappe-jvm,chappe-native", "--spectrum": None}
    positional = []
    while args:
        arg = args.pop(0)
        if arg in options and args:
            options[arg] = args.pop(0)
        else:
            positional.append(arg)
    if len(positional) != 2:
        sys.exit(__doc__)
    subject_list = options["--subject"].split(",")
    spectrum_list = (options["--spectrum"].split(",") if options["--spectrum"]
                     else subject_list + ["helidon", "jetty"])
    main(positional[0], positional[1], subject_list, spectrum_list)
